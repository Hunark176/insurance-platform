-- Credit notes for the premium of the period no longer covered after a policy
-- cancellation (pro rata per day, section 39 VVG). Created by billing from
-- PolicyCancelledEvent; at most one per policy because a policy can be
-- cancelled only once, which also makes repeated event delivery harmless.

create table credit_notes (
    id            bigint generated by default as identity primary key,
    policy_id     bigint                   not null,
    customer_id   bigint                   not null,
    amount        numeric(19, 2)           not null,
    currency      varchar(3)               not null,
    credited_days bigint                   not null,
    term_days     bigint                   not null,
    created_at    timestamp with time zone not null,
    constraint uk_credit_notes_policy_id unique (policy_id),
    constraint ck_credit_notes_amount check (amount > 0),
    constraint ck_credit_notes_days check (credited_days > 0 and credited_days <= term_days)
);
