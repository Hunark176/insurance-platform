-- Stored responses for requests sent with an Idempotency-Key header.
--
-- A client that retries POST /api/claims after a timeout gets the stored first
-- response instead of creating a second claim. A row without status_code is a
-- request still in progress; scope_key (user, method, path, key) is unique, so
-- two concurrent first requests cannot both run. Rows are deleted after the
-- retention period (insurance.idempotency.retention, default 24 hours).

create table idempotency_records (
    id            bigint generated by default as identity primary key,
    scope_key     varchar(400)             not null,
    request_hash  varchar(64)              not null,
    status_code   integer,
    content_type  varchar(200),
    response_body text,
    created_at    timestamp with time zone not null,
    completed_at  timestamp with time zone,
    constraint uk_idempotency_records_scope_key unique (scope_key)
);

create index idx_idempotency_records_created_at on idempotency_records (created_at);
